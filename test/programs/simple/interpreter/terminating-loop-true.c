// A loop whose termination is hard to prove by abstraction, but trivial to
// establish by executing the program.
int collatz(int n) {
  int steps = 0;
  while (n != 1) {
    if (n % 2 == 0) {
      n = n / 2;
    } else {
      n = 3 * n + 1;
    }
    steps++;
  }
  return steps;
}

int main(void) { return collatz(27); }
